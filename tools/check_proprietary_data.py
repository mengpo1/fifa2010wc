#!/usr/bin/env python3
"""Check that no proprietary game data is committed or built (D-007, ROADMAP §4.5).

The project must never contain or produce the user's game files: disc images, XEX
executables, content packages, game assets, C++ generated from the game, or keys.
This script looks for them by name, by size and by content signature.

Modes:
  repo     Files tracked by git in the current repository (default).
  staged   Files staged for the next commit (used by .githooks/pre-commit).
  tree DIR Every file under DIR (used by the Nix check on the flake source).
  store PATH...
           Every file under the given Nix store paths, signature rules only
           (used by the Nix check on the closure of the built packages).

Exit status: 0 when nothing is found, 1 when a finding is reported, 2 on usage error.
Only the Python standard library is used. Run it with `python3 -I`.
"""

import hashlib
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ALLOWLIST_PATH = os.path.join(HERE, "proprietary-data-allowlist.json")

# File names and extensions that are game data or derived from it.
FORBIDDEN_EXTENSIONS = {
    # Disc images and executables
    ".iso", ".xiso", ".god", ".xex", ".xexp", ".xcp", ".dkey",
    # EA archive and asset containers used by the game, raw dumps
    ".big", ".bh", ".bin", ".img", ".dmp",
    # Xbox 360 audio and video containers
    ".xma", ".xwb", ".xsb", ".xgs", ".bik", ".vp6",
    # Save and content packages
    ".stfs", ".xcontent",
}
# Path components that hold private or generated files (ISO_REQUIREMENTS.md §6).
FORBIDDEN_DIRECTORIES = {"generated", "private", "game-files", "xcontent", "454108E4"}
# Build output folders are only forbidden at the repository root, so that a source
# folder named out/ deeper in the tree is not caught by mistake.
FORBIDDEN_TOP_DIRECTORIES = {"out", "build", "result"}

MAX_FILE_SIZE = 1024 * 1024  # 1 MiB (ROADMAP §4.5)

# Content signatures. Offsets are those of the formats, read without decrypting anything.
XEX_MAGICS = (b"XEX2", b"XEX1", b"XEX%", b"XEX-", b"XEX0", b"XEX?")
STFS_MAGICS = (b"CON ", b"LIVE", b"PIRS")
STFS_MIN_SIZE = 0xA000  # the smallest possible STFS package (header and first tables)
XDVDFS_MAGIC = b"MICROSOFT*XBOX*MEDIA"
XDVDFS_SECTOR = 2048
XDVDFS_PARTITIONS = (0x0, 0x2080000, 0xFD90000, 0x18300000)  # plain, XGD3, XGD2, XGD1

# A lone 32 digit hexadecimal token is 128 bits: the size of an AES-128 key. Hashes used
# by the project are longer (git: 40, SHA-256: 64) and are not matched.
HEX128_RE = re.compile(rb"(?<![0-9A-Fa-f])[0-9A-Fa-f]{32}(?![0-9A-Fa-f])")
# C++ generated by `rexglue codegen` (docs/site/pages/codegen/generated-code.md upstream).
GENERATED_MARKERS = (b"// Generated by rexglue", b"DEFINE_REX_FUNC(")
GUEST_FUNCTION_RE = re.compile(rb"\bsub_8[0-9A-F]{7}\b")
GUEST_FUNCTION_LIMIT = 50  # hand-written hooks name a few guest functions, not hundreds
CXX_EXTENSIONS = {".c", ".cc", ".cpp", ".cxx", ".h", ".hh", ".hpp", ".hxx", ".inl", ".inc"}


def load_allowlist():
    """Entries {"path": ..., "sha256": ..., "reason": ...}; a file is skipped only when both
    its path suffix and its content hash match, so an allowlisted file cannot be replaced."""
    if not os.path.exists(ALLOWLIST_PATH):
        return []
    with open(ALLOWLIST_PATH, encoding="utf-8") as f:
        data = json.load(f)
    for entry in data["entries"]:
        if not entry.get("reason"):
            raise SystemExit(f"allowlist entry without a reason: {entry}")
    return data["entries"]


def sha256_of(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def is_allowlisted(path, allowlist):
    normalized = path.replace(os.sep, "/")
    candidates = [e for e in allowlist if normalized.endswith(e["path"])]
    if not candidates:
        return False
    digest = sha256_of(path)
    return any(e["sha256"] == digest for e in candidates)


def read_at(f, offset, size):
    f.seek(offset)
    return f.read(size)


def signature_findings(path, size):
    """Content checks shared by every mode."""
    findings = []
    try:
        with open(path, "rb") as f:
            head = f.read(4)
            if head in XEX_MAGICS:
                findings.append(f"XEX executable signature {head!r} at offset 0")
            if head in STFS_MAGICS and size >= STFS_MIN_SIZE:
                findings.append(f"STFS content package signature {head!r} at offset 0")
            for base in XDVDFS_PARTITIONS:
                offset = base + 32 * XDVDFS_SECTOR
                if size >= offset + len(XDVDFS_MAGIC) and \
                        read_at(f, offset, len(XDVDFS_MAGIC)) == XDVDFS_MAGIC:
                    findings.append(f"Xbox disc image (XDVDFS) signature at offset {offset:#x}")
    except OSError as e:
        findings.append(f"cannot read file: {e}")
    return findings


def text_findings(path, size, rel):
    """Checks for files of the repository itself."""
    findings = []
    if size > 4 * MAX_FILE_SIZE:
        return findings  # already reported as too large; do not load it
    with open(path, "rb") as f:
        data = f.read()
    if b"\0" in data[:8192]:
        return findings  # binary file: covered by the size and signature checks
    for match in HEX128_RE.finditer(data):
        line = data.count(b"\n", 0, match.start()) + 1
        findings.append(f"line {line}: 128-bit hexadecimal token (possible key)")
    ext = os.path.splitext(rel)[1].lower()
    if ext in CXX_EXTENSIONS:
        for marker in GENERATED_MARKERS:
            if marker in data:
                findings.append(f"generated code marker {marker.decode()!r}")
        count = len(GUEST_FUNCTION_RE.findall(data))
        if count > GUEST_FUNCTION_LIMIT:
            findings.append(f"{count} guest function names (generated code?)")
    return findings


def check_repo_file(root, rel, allowlist):
    path = os.path.join(root, rel)
    if os.path.islink(path) or not os.path.isfile(path):
        return []
    findings = []
    parts = rel.replace(os.sep, "/").split("/")
    ext = os.path.splitext(parts[-1])[1].lower()
    if ext in FORBIDDEN_EXTENSIONS:
        findings.append(f"forbidden file type {ext}")
    if parts[0] in FORBIDDEN_TOP_DIRECTORIES:
        findings.append(f"build output folder {parts[0]}/")
    for part in parts[:-1]:
        if part in FORBIDDEN_DIRECTORIES:
            findings.append(f"private or generated folder {part}/")
    size = os.path.getsize(path)
    if size > MAX_FILE_SIZE:
        findings.append(f"file larger than {MAX_FILE_SIZE} bytes ({size})")
    findings += signature_findings(path, size)
    findings += text_findings(path, size, rel)
    if findings and is_allowlisted(path, allowlist):
        return []
    return findings


def check_store_file(path, allowlist):
    if os.path.islink(path) or not os.path.isfile(path):
        return []
    findings = signature_findings(path, os.path.getsize(path))
    if findings and is_allowlisted(path, allowlist):
        return []
    return findings


def git_files(args):
    out = subprocess.run(["git", *args], check=True, capture_output=True).stdout
    return [p for p in out.decode("utf-8").split("\0") if p]


def walk(root):
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d != ".git"]
        for name in filenames:
            yield os.path.relpath(os.path.join(dirpath, name), root)


def report(results, scanned):
    for where, findings in results:
        for finding in findings:
            print(f"{where}: {finding}")
    if results:
        print(f"FAIL: {len(results)} of {scanned} files have findings", file=sys.stderr)
        return 1
    print(f"OK: {scanned} files checked, no proprietary data found")
    return 0


def main(argv):
    mode = argv[1] if len(argv) > 1 else "repo"
    allowlist = load_allowlist()
    results = []
    if mode in ("repo", "staged"):
        root = subprocess.run(["git", "rev-parse", "--show-toplevel"], check=True,
                              capture_output=True, text=True).stdout.strip()
        os.chdir(root)
        files = git_files(["ls-files", "-z"]) if mode == "repo" else \
            git_files(["diff", "--cached", "--name-only", "--diff-filter=ACMR", "-z"])
        for rel in files:
            findings = check_repo_file(root, rel, allowlist)
            if findings:
                results.append((rel, findings))
        return report(results, len(files))
    if mode == "tree" and len(argv) == 3:
        root = argv[2]
        files = list(walk(root))
        for rel in files:
            findings = check_repo_file(root, rel, allowlist)
            if findings:
                results.append((rel, findings))
        return report(results, len(files))
    if mode == "store" and len(argv) >= 3:
        scanned = 0
        for top in argv[2:]:
            paths = [top] if os.path.isfile(top) else \
                [os.path.join(top, rel) for rel in walk(top)]
            for path in paths:
                scanned += 1
                findings = check_store_file(path, allowlist)
                if findings:
                    results.append((path, findings))
        return report(results, scanned)
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
