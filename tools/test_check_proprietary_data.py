#!/usr/bin/env python3
"""Tests for check_proprietary_data.py.

Every sample is synthesized in a temporary folder at run time: the repository itself never
holds a file that trips the checker. Run with `python3 -I tools/test_check_proprietary_data.py`.
"""

import importlib.util
import os
import shutil
import subprocess
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
SPEC = importlib.util.spec_from_file_location(
    "check_proprietary_data", os.path.join(HERE, "check_proprietary_data.py"))
checker = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(checker)


class CheckerTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = self.tmp.name

    def tearDown(self):
        self.tmp.cleanup()

    def write(self, rel, data):
        path = os.path.join(self.root, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "wb") as f:
            f.write(data)
        return rel

    def findings(self, rel, allowlist=()):
        return checker.check_repo_file(self.root, rel, list(allowlist))

    def test_clean_source_file_passes(self):
        rel = self.write("app/README.md", b"# app\n\nPortable application layer.\n")
        self.assertEqual(self.findings(rel), [])

    def test_forbidden_extensions(self):
        for name in ("game.iso", "default.xex", "update.xexp", "data1.big", "dump.bin"):
            with self.subTest(name=name):
                rel = self.write(name, b"not really data\n")
                self.assertTrue(any("forbidden file type" in f for f in self.findings(rel)))

    def test_private_and_generated_folders(self):
        for rel in ("generated/default/a.txt", "src/private/notes.txt", "out/build/x.txt"):
            with self.subTest(rel=rel):
                self.write(rel, b"x\n")
                self.assertTrue(self.findings(rel))

    def test_size_limit(self):
        rel = self.write("big.txt", b"a" * (checker.MAX_FILE_SIZE + 1))
        self.assertTrue(any("larger than" in f for f in self.findings(rel)))

    def test_xex_signature_under_any_name(self):
        rel = self.write("assets/innocent.txt", b"XEX2" + b"\0" * 64)
        self.assertTrue(any("XEX executable" in f for f in self.findings(rel)))

    def test_xdvdfs_signature(self):
        data = bytearray(0x10000 + 64)
        data[0x10000:0x10000 + len(checker.XDVDFS_MAGIC)] = checker.XDVDFS_MAGIC
        rel = self.write("disc.dat", bytes(data))
        self.assertTrue(any("XDVDFS" in f for f in self.findings(rel)))

    def test_stfs_signature_needs_package_size(self):
        small = self.write("note.txt", b"CON notes\n")
        self.assertEqual(self.findings(small), [])
        package = self.write("package.dat", b"CON " + b"\0" * checker.STFS_MIN_SIZE)
        self.assertTrue(any("STFS" in f for f in self.findings(package)))

    def test_128_bit_hex_token(self):
        token = ("0123456789abcdef" * 2).encode()
        rel = self.write("tools/key.py", b"KEY = '" + token + b"'\n")
        self.assertTrue(any("128-bit" in f for f in self.findings(rel)))

    def test_longer_hashes_are_not_tokens(self):
        sha256 = ("0123456789abcdef" * 4).encode()
        git = ("0123456789" * 4).encode()
        rel = self.write("docs/hashes.md", sha256 + b"\n" + git + b"\n")
        self.assertEqual(self.findings(rel), [])

    def test_generated_code(self):
        marked = self.write("hooks/a.cpp", b"// Generated by rexglue\n")
        self.assertTrue(self.findings(marked))
        names = b"".join(b"sub_8%07X();\n" % i for i in range(checker.GUEST_FUNCTION_LIMIT + 1))
        many = self.write("hooks/b.cpp", names)
        self.assertTrue(any("guest function names" in f for f in self.findings(many)))
        few = self.write("hooks/c.cpp", b"REX_HOOK_RAW(sub_82CBD7E0) {}\n")
        self.assertEqual(self.findings(few), [])

    def test_allowlist_requires_matching_hash(self):
        rel = self.write("tests/fixtures/sample.iso", b"synthetic\n")
        path = os.path.join(self.root, rel)
        entry = {"path": "tests/fixtures/sample.iso", "sha256": checker.sha256_of(path),
                 "reason": "test"}
        self.assertEqual(self.findings(rel, [entry]), [])
        wrong = dict(entry, sha256="0" * 64)
        self.assertTrue(self.findings(rel, [wrong]))

    def test_store_mode_uses_signatures_only(self):
        self.write("lib/libfoo.so.bin", b"\x7fELF" + b"\0" * 64)
        xex = self.write("share/x.dat", b"XEX2" + b"\0" * 64)
        self.assertEqual(checker.check_store_file(os.path.join(self.root, "lib/libfoo.so.bin"), []), [])
        self.assertTrue(checker.check_store_file(os.path.join(self.root, xex), []))


class StagedModeTest(unittest.TestCase):
    """The pre-commit hook must check what the commit will hold: the index, not the
    working tree (regression test for the J1 review of PR #2)."""

    XEX_SAMPLE = b"XEX2" + b"\0" * 64
    CLEAN_SAMPLE = b"clean text\n"

    def setUp(self):
        if shutil.which("git") is None:
            self.fail("git is required by the staged mode tests")
        self.tmp = tempfile.TemporaryDirectory()
        self.root = self.tmp.name
        # Hermetic git: no system or user configuration, no hooks.
        self.env = dict(os.environ, GIT_CONFIG_NOSYSTEM="1", GIT_CONFIG_GLOBAL=os.devnull,
                        HOME=self.root)
        self.git("init", "-q")

    def tearDown(self):
        self.tmp.cleanup()

    def git(self, *args):
        subprocess.run(["git", *args], cwd=self.root, env=self.env, check=True,
                       capture_output=True)

    def write(self, rel, data):
        path = os.path.join(self.root, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "wb") as f:
            f.write(data)

    def staged_findings(self):
        old_env = dict(os.environ)
        os.environ.update(self.env)
        try:
            results, scanned = checker.check_staged(self.root, [])
        finally:
            os.environ.clear()
            os.environ.update(old_env)
        return results, scanned

    def test_staged_data_is_caught_when_the_working_tree_is_clean(self):
        # The defect: XEX bytes are staged, then the working copy is replaced by clean
        # text. Reading the working tree let the XEX bytes through to the commit.
        self.write("assets/asset.dat", self.XEX_SAMPLE)
        self.git("add", "assets/asset.dat")
        self.write("assets/asset.dat", self.CLEAN_SAMPLE)
        results, scanned = self.staged_findings()
        self.assertEqual(scanned, 1)
        self.assertEqual([rel for rel, _ in results], ["assets/asset.dat"])
        self.assertTrue(any("XEX executable" in f for f in results[0][1]))

    def test_unstaged_working_tree_change_is_not_what_is_committed(self):
        # The other way round: the index holds clean text; data only in the working tree
        # is not part of this commit (repo mode and CI check tracked files later).
        self.write("assets/asset.dat", self.CLEAN_SAMPLE)
        self.git("add", "assets/asset.dat")
        self.write("assets/asset.dat", self.XEX_SAMPLE)
        results, scanned = self.staged_findings()
        self.assertEqual(scanned, 1)
        self.assertEqual(results, [])

    def test_staged_name_rules_still_apply(self):
        self.write("disc/game.iso", self.CLEAN_SAMPLE)
        self.git("add", "-f", "disc/game.iso")
        results, _ = self.staged_findings()
        self.assertTrue(any("forbidden file type" in f for f in results[0][1]))

    def test_deleted_files_are_not_checked(self):
        self.write("a.txt", self.CLEAN_SAMPLE)
        self.git("add", "a.txt")
        self.git("-c", "user.name=t", "-c", "user.email=t@example.invalid", "commit", "-qm", "a")
        self.git("rm", "-q", "a.txt")
        results, scanned = self.staged_findings()
        self.assertEqual((results, scanned), ([], 0))


if __name__ == "__main__":
    unittest.main(verbosity=2)
